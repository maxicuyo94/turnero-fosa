import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { StorefrontScreen, type PublicProduct } from "@/src/modules/shop/storefront-screen";
import { ShopCheckoutScreen } from "@/src/modules/shop/checkout-screen";
import { saveCart } from "@/src/modules/shop/cart-storage";
import { createShopOrderAction } from "@/app/shop/actions";
const navigation = vi.hoisted(() => ({ push: vi.fn() }));
vi.mock("next/navigation", () => ({ useRouter: () => navigation }));
vi.mock("@/app/shop/actions", () => ({ createShopOrderAction: vi.fn() }));
vi.mock("@/src/components/bot-protection", () => ({ BotProtection: () => null }));
const product: PublicProduct = { id:"filter", sku:"F-01", name:"Filtro de transmisión", brand:"Marca", category:"Transmisión", description:"Detalle", compatibility:"Cadena de transmisión", priceCents:650000, available:2, images:[], fitments:[{yearFrom:2020, yearTo:2024, vehicleModel:{id:"moto",brand:"MARCA",model:"MODELO",variant:"150"}}] };
const config = { checkoutEnabled:true, shippingEnabled:true, shippingFeeCents:250000, shippingPostalCodes:["4400"], pickupInstructions:"Taller · Calle 123" };
beforeEach(() => { localStorage.clear(); sessionStorage.clear(); window.history.replaceState(null, "", "/shop"); vi.clearAllMocks(); vi.stubGlobal("requestAnimationFrame", (fn: () => void) => { fn(); return 0; }); Element.prototype.scrollIntoView = vi.fn(); });
afterEach(() => vi.unstubAllGlobals());
describe("purchase experience", () => {
  it("finds accented names with unaccented words and filters by model and year", () => {
    render(<StorefrontScreen products={[product]} config={config} paymentAvailable />);
    fireEvent.change(screen.getByLabelText("Buscar repuesto"), {target:{value:"filtro transmision"}});
    expect(screen.getByRole("heading",{name:product.name})).toBeInTheDocument();
    fireEvent.click(screen.getByText("Buscar por mi moto"));
    fireEvent.change(screen.getByLabelText("Marca, modelo y versión"), {target:{value:"moto"}});
    fireEvent.change(screen.getByLabelText("Año",{exact:false}), {target:{value:"2019"}});
    expect(screen.getByText("No encontramos repuestos con esos filtros.")).toBeInTheDocument();
    fireEvent.change(screen.getByLabelText("Año",{exact:false}), {target:{value:"2022"}});
    expect(screen.getByRole("heading",{name:product.name})).toBeInTheDocument();
  });
  it("keeps filters when returning from a product and can remove them", () => {
    const view = render(<StorefrontScreen products={[product]} config={config} paymentAvailable />);
    fireEvent.change(screen.getByLabelText("Buscar repuesto"), {target:{value:"transmision"}});
    fireEvent.change(screen.getByLabelText("Categoría"), {target:{value:"Transmisión"}});
    expect(new URLSearchParams(window.location.search).get("q")).toBe("transmision");
    fireEvent.click(screen.getByRole("link",{name:`Ver ficha de ${product.name}`}));
    expect(sessionStorage.getItem("shop-catalog-return-v1")).toContain("transmision");
    view.unmount();
    render(<StorefrontScreen products={[product]} config={config} paymentAvailable />);
    expect(screen.getByLabelText("Buscar repuesto")).toHaveValue("transmision");
    expect(screen.getByLabelText("Categoría")).toHaveValue("Transmisión");
    fireEvent.click(screen.getByRole("button",{name:"Limpiar todos"}));
    expect(window.location.search).toBe("");
  });
  it("checks coverage before collecting contact and preserves delivery selections", () => {
    act(() => saveCart([{productId:product.id,quantity:1,unitPriceCents:product.priceCents}]));
    const view = render(<ShopCheckoutScreen products={[product]} config={config} paymentAvailable />);
    fireEvent.click(screen.getByRole("button", {name:"Elegir entrega"}));
    fireEvent.change(screen.getByLabelText("Cómo lo recibís"), {target:{value:"SHIPPING"}});
    expect(screen.queryByLabelText("Nombre y apellido")).not.toBeInTheDocument();
    fireEvent.change(screen.getByLabelText("Código postal"), {target:{value:"9999"}});
    expect(screen.getByText(/Todavía no enviamos a ese código postal/)).toBeInTheDocument();
    expect(screen.getByRole("button",{name:"Revisar pedido"})).toBeDisabled();
    fireEvent.change(screen.getByLabelText("Código postal"), {target:{value:"4400"}});
    expect(screen.getByLabelText("Localidad")).toHaveValue("Salta");
    expect(screen.getByLabelText("Localidad")).toHaveAttribute("readonly");
    expect(screen.getByLabelText("Provincia")).toHaveValue("Salta");
    expect(screen.getByText(/solo dentro de la ciudad de Salta/u)).toBeInTheDocument();
    fireEvent.change(screen.getByLabelText("Comprás como"), {target:{value:"MECHANIC"}});
    fireEvent.change(screen.getByLabelText("Nombre y apellido"), {target:{value:"Comprador de prueba"}});
    view.unmount();
    render(<ShopCheckoutScreen products={[product]} config={config} paymentAvailable />);
    fireEvent.click(screen.getByRole("button", {name:"Elegir entrega"}));
    expect(screen.getByLabelText("Cómo lo recibís")).toHaveValue("SHIPPING");
    expect(screen.getByLabelText("Comprás como")).toHaveValue("MECHANIC");
    expect(screen.getByLabelText("Nombre y apellido")).toHaveValue("Comprador de prueba");
  });
  it("allows quantity editing but blocks above stock and never blames the price", () => {
    act(() => saveCart([{productId:product.id,quantity:1,unitPriceCents:product.priceCents}]));
    render(<ShopCheckoutScreen products={[product]} config={config} paymentAvailable />);
    const quantity = screen.getByLabelText(`Cantidad de ${product.name}`) as HTMLInputElement;
    fireEvent.change(quantity, {target:{value:""}});
    expect(quantity).toHaveValue("");
    fireEvent.change(quantity, {target:{value:"3"}});
    expect(quantity.validity.patternMismatch).toBe(true);
    fireEvent.click(screen.getByRole("button", {name:"Elegir entrega"}));
    expect(screen.queryByLabelText("Nombre y apellido")).not.toBeInTheDocument();
    expect(screen.getByText("Ingresá entre 1 y 2 unidades.")).toBeInTheDocument();
    expect(screen.queryByText(/Cambió el precio/)).not.toBeInTheDocument();
    fireEvent.change(quantity, {target:{value:"2"}}); fireEvent.blur(quantity);
    expect(quantity).toHaveValue("2");
    expect(screen.getByRole("button",{name:`Agregar una unidad de ${product.name}`})).toBeDisabled();
  });
  it("reviews the address and total before enabling final order creation", () => {
    act(() => saveCart([{productId:product.id,quantity:1,unitPriceCents:product.priceCents}]));
    render(<ShopCheckoutScreen products={[product]} config={config} paymentAvailable={false} />);
    fireEvent.click(screen.getByRole("button", {name:"Elegir entrega"}));
    fireEvent.change(screen.getByLabelText("Nombre y apellido"), {target:{value:"Comprador"}});
    fireEvent.change(screen.getByLabelText("Email"), {target:{value:"buyer@test.invalid"}});
    fireEvent.change(screen.getByLabelText("Teléfono"), {target:{value:"1155555555"}});
    fireEvent.click(screen.getByRole("button",{name:"Revisar pedido"}));
    expect(screen.getByRole("heading",{name:"Confirmá los datos de tu compra"})).toBeInTheDocument();
    expect(screen.getByRole("button",{name:"Confirmar pedido y continuar"})).toBeDisabled();
    expect(screen.getByText("Comprador")).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button",{name:"Editar entrega y datos"}));
    expect(screen.getByLabelText("Nombre y apellido")).toHaveValue("Comprador");
  });

  it("reuses the purchase intent on retry and remembers the resulting private order", async () => {
    act(() => saveCart([{productId:product.id,quantity:1,unitPriceCents:product.priceCents}]));
    const create = vi.mocked(createShopOrderAction);
    const attempts: string[] = [];
    create.mockImplementation(async (_, form) => {
      attempts.push(String(form.get("requestKey")));
      expect(form.get("fullName")).toBe("Comprador");
      expect(form.get("deliveryKind")).toBe("PICKUP");
      expect(JSON.parse(String(form.get("items")))).toEqual([{productId:product.id,quantity:1,unitPriceCents:product.priceCents}]);
      return attempts.length === 1 ? {error:"Conexión interrumpida. Reintentá."} : {orderUrl:`/shop/order?token=${String(form.get("accessToken"))}`};
    });
    render(<ShopCheckoutScreen products={[product]} config={config} paymentAvailable />);
    fireEvent.click(screen.getByRole("button", {name:"Elegir entrega"}));
    fireEvent.change(screen.getByLabelText("Nombre y apellido"), {target:{value:"Comprador"}});
    fireEvent.change(screen.getByLabelText("Email"), {target:{value:"buyer@test.invalid"}});
    fireEvent.change(screen.getByLabelText("Teléfono"), {target:{value:"1155555555"}});
    fireEvent.click(screen.getByRole("button",{name:"Revisar pedido"}));
    expect(create).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button",{name:"Confirmar pedido y continuar"}));
    const error = await screen.findByText("Conexión interrumpida. Reintentá.");
    expect(error.parentElement).toHaveFocus();
    fireEvent.click(screen.getByRole("button",{name:"Confirmar pedido y continuar"}));
    await waitFor(() => expect(navigation.push).toHaveBeenCalledWith(expect.stringMatching(/^\/shop\/order\?token=[a-f0-9]{64}$/u)));
    expect(attempts).toHaveLength(2); expect(attempts[1]).toBe(attempts[0]);
    expect(JSON.parse(localStorage.getItem("taller-shop-cart-v1")!)).toEqual([]);
    expect(sessionStorage.getItem("shop-last-order-v1")).toContain("/shop/order?token=");
    expect(sessionStorage.getItem("shop-checkout-draft-v1")).toBeNull();
  });
});
